func runEvents(t *testing.T, granular bool, agent AgentAdapter, script ...ScriptStep) []Event {
	t.Helper()
	rec := &eventRecorder{}
	sim, _ := userSim("generated by the simulator")
	cfg := baseConfig(agent, sim)
	cfg.Script = script
	opts := []RunOption{WithEventListener(rec.record)}
	if granular {
		opts = append(opts, WithGranularEventsForRun(true))
	}
	Run(context.Background(), cfg, opts...)
	return rec.all()
}

func count(events []Event, t EventType) int {
	n := 0
	for _, e := range events {
		if e.Type == t {
			n++
		}
	}
	return n
}

func TestGranularIsOptIn(t *testing.T) {
	t.Parallel()
	events := runEvents(t, false, &echoAgent{text: "ok"}, User("hi"), Agent(), Succeed())
	if count(events, EventTextMessageStart) != 0 || count(events, EventMessageSnapshot) != 2 {
		t.Fatalf("default must be snapshot mode: %v", typesOf(events))
	}
	events = runEvents(t, true, &echoAgent{text: "ok"}, User("hi"), Agent(), Succeed())
	if count(events, EventMessageSnapshot) != 0 || count(events, EventTextMessageEnd) != 2 {
		t.Fatalf("granular run: %v", typesOf(events))
	}
}

func typesOf(events []Event) []EventType {
	out := make([]EventType, len(events))
	for i, e := range events {
		out[i] = e.Type
	}
	return out
}

func TestGranularEventsAreOrderedAndEndOnce(t *testing.T) {
	t.Parallel()
	events := runEvents(t, true, streamingAgent, User("hi"), Agent(), User(), Agent(), Succeed())
	ended := map[string]int{}
	started := map[string]bool{}
	for i, e := range events {
		if e.Seq != uint64(i+1) {
			t.Fatalf("seq %d at position %d", e.Seq, i)
		}
		p := decode(t, e.Payload)
		switch e.Type {
		case EventTextMessageStart:
			started[p["messageId"].(string)] = true
		case EventTextMessageEnd:
			id := p["messageId"].(string)
			ended[id]++
			if !started[id] {
				t.Errorf("END before START for %s", id)
			}
		}
	}
	for id, n := range ended {
		if n != 1 {
			t.Errorf("message %s ended %d times", id, n)
		}
	}
	if len(ended) != 4 {
		t.Errorf("expected 4 messages, got %d", len(ended))
	}
}

func TestNonStreamedToolCallsOnlyInEndMessage(t *testing.T) {
	t.Parallel()
	events := runEvents(t, true, toolCallingAgent, User("hi"), Agent(), Succeed())
	if count(events, EventToolCallStart)+count(events, EventToolCallArgs)+count(events, EventToolCallEnd) != 0 {
		t.Fatalf("non-streamed tool calls must not emit TOOL_CALL_*: %v", typesOf(events))
	}
	for _, e := range events {
		if e.Type == EventTextMessageEnd {
			msg := decode(t, e.Payload)["message"].(map[string]any)
			if msg["role"] == "assistant" && msg["toolCalls"] != nil {
				return
			}
		}
	}
	t.Fatal("END.message must carry the toolCalls")
}

