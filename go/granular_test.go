func TestStreamAbortReconcilesWithSnapshot(t *testing.T) {
	t.Parallel()
	aborting := AgentFunc(func(_ context.Context, in AgentInput) (*AgentReturn, error) {
		in.Stream.TextDelta("half a sent")
		return nil, errors.New("connection dropped")
	})
	events := runEvents(t, true, aborting, User("hi"), Agent())
	types := typesOf(events)
	i := slices.Index(types, EventTextMessageContent)
	if i < 0 || !slices.Contains(types[i:], EventMessageSnapshot) || slices.Contains(types[i:], EventTextMessageEnd) {
		t.Fatalf("an aborted stream must be reconciled by a snapshot, not an END: %v", types)
	}
}

func TestSnapshotTimestampsStrictlyIncrease(t *testing.T) {
	deterministic(t) // frozen clock
	rollbacks := AgentFunc(func(_ context.Context, in AgentInput) (*AgentReturn, error) {
		in.ScenarioState.RollbackMessagesTo(0)
		in.ScenarioState.RollbackMessagesTo(0)
		return TextReturn("again"), nil
	})
	events := runEvents(t, true, rollbacks, User("hi"), Agent(), User("more"), Agent(), Succeed())
	last := int64(0)
	for _, e := range events {
		if e.Type != EventMessageSnapshot {
			continue
		}
		if e.Timestamp <= last {
			t.Fatalf("snapshot timestamps must strictly increase: %d after %d", e.Timestamp, last)
		}
		last = e.Timestamp
	}
	if last == 0 {
		t.Fatal("expected rollback snapshots")
	}
}

