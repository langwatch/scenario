// Builds js/.build/internals.mjs: the few JS SDK functions the micro
// benchmarks call that dist does not export (the AG-UI converter, the
// event reporter and the Twilio µ-law/resample codecs). It bundles them
// from javascript/src with the package's own tsup (a devDependency, so no
// install), with every import bundled in, so the result loads from here.
// Everything else the benchmarks call comes from dist.
//
//   node js/build-internals.mjs
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { BENCH_DIR, JS_PKG_DIR } from "./lib/paths.mjs";

const outDir = path.join(BENCH_DIR, "js", ".build");
fs.mkdirSync(outDir, { recursive: true });

const src = (p) => JSON.stringify(path.join(JS_PKG_DIR, "src", p));
const entry = path.join(outDir, "internals.ts");
fs.writeFileSync(
  entry,
  `// Generated by build-internals.mjs; do not edit.
export { convertModelMessagesToAguiMessages } from ${src("utils/convert-core-messages-to-agui-messages")};
export { EventReporter } from ${src("events/event-reporter")};
export {
  mulawToPcm16,
  pcm16ToMulaw,
  resamplePcm16,
  mulaw8kToPcm16At24k,
  pcm16At24kToMulaw8k,
} from ${src("voice/adapters/twilio-shared")};
`
);

const tsupEntry = path.join(JS_PKG_DIR, "node_modules", "tsup", "dist", "index.js");
if (!fs.existsSync(tsupEntry)) {
  throw new Error(`tsup not found at ${tsupEntry}; run pnpm install in the javascript package first`);
}
const tsup = await import(pathToFileURL(tsupEntry).href);
const build = tsup.build ?? tsup.default?.build;
// tsup reads package.json and tsconfig from the working directory.
process.chdir(JS_PKG_DIR);
await build({
  config: false,
  entry: { internals: entry },
  outDir,
  format: ["esm"],
  platform: "node",
  target: "node20",
  tsconfig: path.join(JS_PKG_DIR, "tsconfig.json"),
  dts: false,
  splitting: false,
  sourcemap: false,
  clean: false,
  silent: true,
  // Bundle every dependency, so nothing has to resolve from js/.build.
  noExternal: [/.*/],
  // CommonJS dependencies bundled into ESM call require() for Node
  // built-ins; give them one.
  banner: { js: 'import { createRequire as __cr } from "node:module"; const require = __cr(import.meta.url);' },
});

const out = path.join(outDir, "internals.mjs");
if (!fs.existsSync(out)) {
  // tsup names ESM output .js when it thinks the package is "type": "module".
  const alt = path.join(outDir, "internals.js");
  if (fs.existsSync(alt)) fs.renameSync(alt, out);
}
if (!fs.existsSync(out)) throw new Error(`build produced no ${out}`);
console.log(`built ${out}`);
